#ask user for a number, then another number
num1 = float(input("Enter the first number: "))
num2 = float(input("Enter the second number: "))

#add the two numbers
sum_result = num1 + num2

#subtract the numbers
subtract_result = num1 - num2   

#display the added and subtracted results
print("The sum of", num1, "and", num2, "is:", sum_result)
print("when", num2, "is subtracted from", num1, "you get:", subtract_result)

#now ask the user for two more numbers
num3 = float(input("Enter the third number: "))
num4 = float(input("Enter the fourth number: "))



#multiply the two numbers
multiply_result = num3 * num4
#divide the two numbers
divide_result = num3 / num4

#display the multiplied and divided results
print(num3, "times", num4, "is:", multiply_result)
print("when", num3, "is divided by", num4, "you get:", divide_result)

